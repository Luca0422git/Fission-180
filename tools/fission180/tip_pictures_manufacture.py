# -- ACTIONS -----------------------------------------------------------------------------------
def _three_ops(b):
    return [
        operation(b, "face", {"type": "flat", "diameter": 12, "number": 1}),
        operation(b, "pocket2d", {"type": "flat", "diameter": 6, "number": 2}, **POCKET),
        operation(b, "drill", {"type": "drill", "diameter": 8, "number": 3}, **HOLES),
    ]


@tp.picture("cam_generate.png")
def generate():
    """The setup's operations before Generate (no toolpath) and after it (every toolpath)."""
    b = plate()
    ops = _three_ops(b)
    enter(b, [])
    try:
        ws.look((-1, 1, -0.9))
        before = cam_render()
        from fission180 import manufacture_ui

        manufacture_ui.show_ops(tp.doc(), [o.Name for o in ops])
        tp.settle()
        after = cam_render()
        return tp.before_after(before, after)
    finally:
        leave()


@tp.picture("cam_simulate.png")
def simulate():
    from fission180 import manufacture_simulate_ui

    b = plate()
    _three_ops(b)
    enter(b, [])
    try:
        ws.look((-1, 1, -0.9))
        tp.run_command("Fission180_CamSimulate")
        tp.wait_for(
            lambda: manufacture_simulate_ui.OPEN.get("player") is not None, "the Simulate player"
        )
        player = manufacture_simulate_ui.OPEN["player"]
        player.seek(0.7)
        tp.settle()
        shot = cam_render()
        image = tp.grab(player)
        player.close()
        tp.settle()
        return tp.with_dialog(shot, image, width=150)
    finally:
        leave()


def _window_picture(command, find):
    b = plate()
    _three_ops(b)
    enter(b, [])
    try:
        tp.run_command(command)
        tp.wait_for(lambda: find() is not None, "the %s window" % command)
        window = find()
        tp.settle()
        image = tp.grab(window)
        window.close()
        tp.settle()
        return tp.dialog_picture(image)
    finally:
        leave()


