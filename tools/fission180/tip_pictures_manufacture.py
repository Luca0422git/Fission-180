def operation(b, kind, tool, **pick):
    """Add and generate the operation (as OK in its dialog does)."""
    from fission180 import manufacture, manufacture_ui

    step = {"op": "cam_operation", "id": kind, "setup": "setup", "kind": kind, "tool": tool}
    step.update(pick)
    step["generate"] = False
    ws.build(b, step)
    op = b.objects[kind]
    # generated as the app does it: FreeCAD's CAM in a program of its own, in the background
    # (in this window FreeCAD's Adaptive looks for a 3D view of its own and fails)
    manufacture_ui.generate([op])
    if not manufacture_ui.wait_generated(600):
        raise RuntimeError("the %s toolpath was not generated in 10 minutes" % kind)
    tp.settle()
    state = manufacture.state(op)
    if state != "valid":
        raise RuntimeError(
            "the %s toolpath is %s: %s" % (kind, state, manufacture.result(op).get("error"))
        )
    return op


def enter(b, ops=()):
    """The MANUFACTURE workspace, the setup active, the toolpaths of `ops` drawn. The
    workspace's lines are drawn SCALE times as wide while the pictures are made (the render is
    made that much larger, then scaled down: they keep the width the window shows)."""
    from fission180 import manufacture_ui, manufacture_view

    if "_lines" not in _SAVED:
        _SAVED["_lines"] = manufacture_view._lines

        def wide(polylines, color, width=2.0):
            return _SAVED["_lines"](polylines, color, width * tp.SCALE)

        manufacture_view._lines = wide
    if not manufacture_ui.enter_workspace():
        raise RuntimeError("the MANUFACTURE workspace did not open")
    tp.settle()
    manufacture_ui.set_active_setup(b.objects["setup"])
    manufacture_ui.show_ops(tp.doc(), [o.Name for o in ops])
    tp.settle()


_SAVED = {}


def leave():
    try:
        from fission180 import manufacture_ui, manufacture_view

        manufacture_ui.leave_workspace()
        tp.settle()
        if "_lines" in _SAVED:
            manufacture_view._lines = _SAVED.pop("_lines")
    except Exception as exc:
        tp.log("leaving MANUFACTURE: %s" % exc)


def cam_render(highlight=None):
    """A render of the workspace as it shows now."""
    return tp.render(highlight=highlight)


def picked(b, op):
    """{body: names} of what the operation machines (its picks), for the highlight."""
    out = {}
    for obj, sub in _picks(op):
        out.setdefault(obj, []).append(sub)
    return out


def _picks(op):
    from fission180 import manufacture

    return [(o, sub) for o, sub in manufacture.op_picks(op) if sub]


def toolpath_picture(b, op, camera=(-1, 1, -0.9), zoom=1.0):
    enter(b, [op])
    try:
        ws.look(camera, zoom=zoom)
        return tp.finish(cam_render(highlight=picked(b, op)))
    finally:
        leave()


