@tp.picture("cam_contour3d.png")
def contour3d():
    """The part and the 3D Contour dialog (its passes at constant heights are hard to see on
    a small demo part, and FreeCAD's engine found none on a plain box's walls)."""
    from fission180 import manufacture_op_ui

    b = round_part()
    enter(b)
    try:
        ws.look((-1, 1, -0.9))
        shot = cam_render()
        manufacture_op_ui.open_operation(tp.doc(), "contour3d")
        panel = tp.wait_for_panel()
        tp.settle()
        image = ws.trim_panel(tp.grab(panel))
        return tp.with_dialog(shot, image, width=170)
    finally:
        try:
            import FreeCADGui as Gui

            if Gui.Control.activeDialog():
                Gui.Control.closeDialog()
        except Exception:
            pass
        leave()


