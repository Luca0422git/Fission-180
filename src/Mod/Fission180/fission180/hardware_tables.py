def as568():
    """{"012": (inside diameter, cross section)} of every dash number, inches."""
    found = dict(AS568_SMALL)
    for first, (section, insides) in AS568_SERIES.items():
        for i, inside in enumerate(insides):
            found["%03d" % (first + i)] = (inside, section)
    return found


def oring_metric():
    """{"10x2": (inside diameter, cross section)} of the metric O-rings, mm."""
    found = {}
    for section, insides in ORING_METRIC.items():
        for inside in insides:
            found["%gx%g" % (inside, section)] = (float(inside), float(section))
    return found
