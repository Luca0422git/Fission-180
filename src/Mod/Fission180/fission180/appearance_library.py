def row_look(row):
    """A library row as a look (the dict designs store)."""
    key, label, group, color, shininess, transparency, extras = row
    look = {
        "key": key,
        "label": label,
        "group": group,
        "color": list(color),
        "shininess": shininess,
        "transparency": transparency,
    }
    if extras:
        look.update(extras)
    return look


def looks():
    return [row_look(row) for row in ROWS]


def find(key):
    for row in ROWS:
        if row[0] == key:
            return row_look(row)
    return None


def words(text):
    return [w for w in str(text or "").lower().replace(",", " ").split() if w]


def matches(look, text):
    """Search: every word typed is in the look's name or category ("anod red", "oak")."""
    hay = (look.get("label", "") + " " + look.get("group", "")).lower()
    return all(word in hay for word in words(text))


def search(text, source=None):
    """The looks whose name or category has every word of `text` (all of them for no text)."""
    source = looks() if source is None else source
    return [look for look in source if matches(look, text)]


def in_category(category, source=None):
    source = looks() if source is None else source
    return [look for look in source if look.get("group") == category]
