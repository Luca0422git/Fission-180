"""The MANUFACTURE and ANIMATION AI tools with the window open (wave 7, builder
workspaces-2), called through the bridge's own entry as the chat panel calls it. The
headless test (Fission180Tests/headless/workspace_tools.py) checks every tool's numbers;
here: what only the window has.

A plate with a clamp on it (four bodies in three components). From Design: cam_setup and
cam_operation make a setup and a facing operation, the toolpath generated by the engine in
its own command-line FreeCAD while the window waits; each is one undo step named "AI: ...".
In Manufacture (the workspace menu) the browser shows what the AI made; cam_edit suppresses
the operation and the browser's row follows; cam_simulate and cam_post answer their numbers
and the file. In Animation: anim_storyboard, anim_explode and anim_callout show up in the
ANIMATION TIMELINE (tabs, bars) and in the view without a click; anim_publish_video renders
the view to an AVI whose frames are counted, refuses MP4 with where to get ffmpeg when
there is none, and does not replace a file without asking; undo takes the callout back.
The design's bodies and components are as they were."""

import json
import os

import FreeCAD as App

from Fission180Tests.gui import animation_steps as a
from Fission180Tests.gui import cam_steps as cam
from Fission180Tests.gui import harness as h
from Fission180Tests.gui import simsetup_steps as st

s = {}


def call(tool, args):
    from fission180.ai import bridge

    try:
        answer = bridge.call(tool, args, from_chat=True)
    except Exception as exc:  # (the bridge must never raise: that is a failure too)
        answer = {"text": "raised %s" % exc, "is_error": True, "image_png_base64": None}
    s["last"] = answer
    return answer


def data(answer):
    text = answer["text"]
    start = text.find("{")
    return json.loads(text[start:]) if start >= 0 else {}


def ok(name, answer, extra=True):
    return h.check(name, not answer["is_error"] and extra, answer["text"][:500])


def undo_names():
    return list(App.ActiveDocument.UndoNames)


def volumes():
    from fission180 import bodies

    return sorted(round(b.Shape.Volume, 3) for b in bodies.solid_bodies(App.ActiveDocument))


# -- Manufacture, from Design ---------------------------------------------------------------------
def setup_from_design():
    for name in ("ai-plate.nc", "ai-explode.avi", "ai-explode.mp4"):  # (of an earlier run)
        if os.path.isfile(os.path.join(h.OUT_DIR, name)):
            os.remove(os.path.join(h.OUT_DIR, name))
    s["volumes"] = volumes()
    s["placements"] = a.design_placements()
    answer = call("cam_tools", {"library": "sample:mm", "type": "flat", "diameter": 10})
    ok("cam_tools lists the 10 mm end mill", answer, len(data(answer).get("tools", [])) == 1)
    answer = call(
        "cam_setup",
        {"bodies": ["Plate"], "stock": {"mode": "relative", "side": 2, "top": 1}},
    )
    info = data(answer)
    ok("cam_setup made Setup1 of the Plate's body", answer, info.get("name") == "Setup1")
    box = info.get("stock_box") or [0] * 6
    h.check(
        "its stock is the 60 x 40 x 6 plate plus 2 mm around and 1 mm on top",
        [round(box[3] - box[0], 3), round(box[4] - box[1], 3), round(box[5] - box[2], 3)]
        == [64.0, 44.0, 7.0],
        box,
    )
    h.check(
        "one undo step named after the call",
        undo_names()[:1] == ["AI: New Setup"],
        undo_names()[:2],
    )
    h.check(
        "still in the Design workspace",
        a.tab_visible("solid") and not cam.ui_module().in_workspace(),
    )


def face_from_design():
    before = undo_names()
    answer = call(
        "cam_operation",
        {"kind": "face", "tool": {"library": "sample:mm", "id": "sample-mm-flat-10"}},
    )
    info = data(answer)
    ok("cam_operation made Face1 with its toolpath", answer, info.get("state") == "valid")
    path = info.get("toolpath") or {}
    h.check("the toolpath is down at the plate's top (Z -1)", path.get("min_cut_z") == -1.0, path)
    h.check(
        "the engine ran beside the window: the toolpath is in the design",
        cam.state("Face1") == "valid" and len(cam.cam().toolpath(cam.op("Face1"))) > 100,
    )
    h.check(
        "one more undo step, named after the call",
        undo_names()[:1] == ["AI: New operation (face)"] and len(undo_names()) == len(before) + 1,
        undo_names()[:3],
    )
    answer = call("cam_operation", {"kind": "pocket2d", "tool": {"type": "flat", "diameter": 6}})
    h.check(
        "an operation without geometry is refused and nothing is added",
        answer["is_error"]
        and "Nothing is selected" in answer["text"]
        and len(cam.operations()) == 1,
        answer["text"][:300],
    )
    h.check(
        "and leaves no undo step",
        undo_names()[:1] == ["AI: New operation (face)"],
        undo_names()[:2],
    )
    h.check("Manufacture from the workspace menu", cam.enter())


def in_manufacture():
    labels = cam.browser_labels()
    h.check(
        "the browser shows the AI's setup and operation",
        "Setup1" in labels and any("Face1" in x for x in labels),
        labels,
    )
    answer = call("cam_edit", {"target": "Face1", "suppressed": True})
    ok("cam_edit suppressed Face1", answer, "suppressed" in answer["text"])


def suppressed_shown():
    h.check("the operation is suppressed in the design", cam.state("Face1") == "suppressed")
    answer = call("cam_simulate", {})
    h.check(
        "cam_simulate has nothing to simulate and says so",
        answer["is_error"] and "no operation to simulate" in answer["text"],
        answer["text"][:300],
    )
    answer = call("cam_edit", {"target": "Face1", "suppressed": False})
    ok("cam_edit brought it back, its toolpath still valid", answer, cam.state("Face1") == "valid")
    answer = call("cam_simulate", {})
    info = data(answer)
    ok("cam_simulate answers the numbers", answer, info.get("collisions") == [])
    # the millimetre on top of the 64 x 44 stock
    h.check(
        "about 64 x 44 x 1 mm3 removed",
        2500 < info.get("removed_mm3", 0) < 2900,
        info.get("removed_mm3"),
    )
    h.check("with the machining time", info.get("time_s", 0) > 0, info.get("time_s"))
    s["nc"] = os.path.join(h.OUT_DIR, "ai-plate.nc")
    answer = call("cam_post", {"path": s["nc"], "program": "7"})
    info = data(answer)
    ok(
        "cam_post wrote the program",
        answer,
        os.path.isfile(s["nc"]) and info.get("file") == s["nc"],
    )
    h.check(
        "the checker found no problem",
        (info.get("check") or {}).get("problems") == [],
        info.get("check"),
    )
    answer = call("cam_setups", {})
    rows = data(answer).get("setups") or [{}]
    ok(
        "cam_setups reads the browser",
        answer,
        [o["name"] for o in rows[0].get("operations", [])] == ["Face1"],
    )
    a.enter()


# -- Animation ------------------------------------------------------------------------------------
def storyboard():
    h.check(
        "Animation is shown (Manufacture was left)",
        a.ui_module().in_workspace() and not cam.ui_module().in_workspace(),
    )
    if a.ui_module().recording():
        h.ribbon("View")
    answer = call("anim_storyboard", {"name": "Explode"})
    ok("anim_storyboard made Explode", answer, data(answer).get("active") == "Explode")


storyboard.done = lambda: "Explode" in a.tabs()
storyboard.done_what = "the ANIMATION TIMELINE shows the AI's storyboard tab"


def explode():
    h.check("its tab is the one in front", a.current() == "Explode", (a.current(), a.tabs()))
    answer = call("anim_explode", {"at": 2})
    info = data(answer)
    moved = {row["component"]: row["position"] for row in info.get("components_at", [])}
    ok(
        "anim_explode moved the Clamp 15 mm up",
        answer,
        # (the Jaw and the Screw are in the Clamp: they are 15 mm up with it)
        sorted(moved) == ["Clamp", "Jaw", "Screw"] and abs(moved["Clamp"][2] - 15.0) < 1e-6,
    )
    h.check(
        "one undo step named after the call",
        undo_names()[:1] == ["AI: Auto Explode (One Level)"],
        undo_names()[:2],
    )


explode.done = lambda: len(a.actions("transform")) == 1 and len(a.canvas().rows) >= 1
explode.done_what = "the timeline shows the Clamp's bar"


def exploded_shown():
    h.check(
        "the bar is the Clamp's, 0 to 2 s", a.spans("transform", "Clamp") == [(0.0, 2.0)], a.spans()
    )
    a.click_time(2.0)


def at_two():
    h.check(
        "at 2 s the view draws the Clamp 15 up",
        a.close(a.shown("Clamp"), (0, 0, 15)),
        a.shown("Clamp"),
    )
    answer = call("anim_transform", {"at": 4, "of": ["Jaw"], "move": [-10, 0, 0]})
    ok(
        "anim_transform moved the Jaw inside the Clamp",
        answer,
        len(data(answer).get("actions", [])) == 1,
    )
    answer = call("anim_callout", {"at": 2, "text": "Clamp", "point": [30, 20, 31], "of": "Clamp"})
    ok("anim_callout pinned a note to the Clamp", answer)


at_two.done = lambda: len(a.view_module().drawn_callouts(a.doc())) == 1
at_two.done_what = "the view draws the callout"


def read_and_publish():
    answer = call("anim_storyboards", {"storyboard": "Explode", "at": 4})
    info = data(answer)
    kinds = sorted(x["kind"] for x in info.get("actions", []))
    ok(
        "anim_storyboards reads the three actions",
        answer,
        kinds == ["callout", "transform", "transform"],
    )
    s["avi"] = os.path.join(h.OUT_DIR, "ai-explode.avi")
    answer = call(
        "anim_publish_video",
        {"path": s["avi"], "width": 320, "height": 240, "fps": 12},
    )
    info = data(answer)
    ok(
        "anim_publish_video wrote the AVI",
        answer,
        os.path.isfile(s["avi"]) and info.get("file") == s["avi"],
    )
    from fission180 import animation_video, animation_video_core as video

    found = video.avi_info(s["avi"]) if os.path.isfile(s["avi"]) else {}
    # 4 s at 12 frames a second
    h.check(
        "49 frames of 320 x 240",
        (found.get("frames"), found.get("width"), found.get("height")) == (49, 320, 240),
        found,
    )
    h.check(
        "the answer says so",
        info.get("frames") == 49 and info.get("length_s") == round(49 / 12.0, 3),
        info,
    )
    h.check("the playhead is where it was", abs(a.playhead() - 2.0) < 1e-6, a.playhead())
    from fission180.ai import bridge

    asked = []
    before = bridge.ASK
    bridge.ASK = lambda title, text: asked.append(text) or False  # (the person says No)
    try:
        answer = call("anim_publish_video", {"path": s["avi"]})
    finally:
        bridge.ASK = before
    h.check(
        "over a file that exists the person is asked, and No keeps the file",
        answer["is_error"] and len(asked) == 1 and "ai-explode.avi" in answer["text"],
        (asked, answer["text"][:300]),
    )
    if animation_video.ffmpeg() is None:
        answer = call("anim_publish_video", {"path": s["avi"][:-4] + ".mp4", "format": "mp4"})
        h.check(
            "MP4 without ffmpeg is refused with where to get it",
            answer["is_error"] and "ffmpeg.org/download.html" in answer["text"],
            answer["text"][:300],
        )
    answer = call("undo", {})
    ok("undo takes the callout back", answer, "AI: Create Callout" in answer["text"])


read_and_publish.timeout_s = 300
read_and_publish.done = lambda: len(a.view_module().drawn_callouts(a.doc())) == 0
read_and_publish.done_what = "the callout is gone from the view"


def leave():
    h.check(
        "the storyboard has its two moves",
        len(a.actions("transform")) == 2 and a.actions("callout") == [],
    )
    st.workspace("Design")


leave.done = lambda: not a.ui_module().in_workspace() and a.tab_visible("solid")
leave.done_what = "Design is shown"


def untouched():
    h.check("no body changed", volumes() == s["volumes"], volumes())
    h.check("no component moved", a.design_placements() == s["placements"])
    h.check("the design timeline is back", a.timeline_visible() and not a.timeline_shown())


h.run(
    "book_workspaces_ai_tools",
    [
        a.new_assembly("AiWs", build=a.nested),
        setup_from_design,
        face_from_design,
        in_manufacture,
        suppressed_shown,
        storyboard,
        explode,
        exploded_shown,
        at_two,
        read_and_publish,
        leave,
        untouched,
    ],
    paced_by="state",
)
